      setCloudUrl(saved)
      setConnectionMode('cloud')
      setCloudTest('ok')
      setCloudLive(true)
      setCloudPanelOpen(false)
      setCloudMessage(
        result.version
          ? `Guardado y conectado · ControlStock v${result.version}`
          : 'URL guardada y conectada a la nube'
      )
