  async function guardarMovimientosCfg(next: boolean) {
    setSavingMovimientosCfg(true)
    setOpCfgError('')
    setOpCfgSaved(null)
    const prev = dobleVerificacionMovimientos
    setDobleVerificacionMovimientos(next)
    try {
      const cfg = await httpApi<{ doble_verificacion: boolean }>('/api/configuracion/movimientos', {
        method: 'PUT',
        body: JSON.stringify({ doble_verificacion: next })
      })
      setDobleVerificacionMovimientos(cfg.doble_verificacion)
      setOpCfgSaved('movimientos')
      setTimeout(() => setOpCfgSaved(null), 2500)
    } catch (err) {
      setDobleVerificacionMovimientos(prev)
      setOpCfgError(
        err instanceof Error ? err.message : 'No se pudo guardar la configuración de movimientos'
      )
    } finally {
      setSavingMovimientosCfg(false)
    }
  }

